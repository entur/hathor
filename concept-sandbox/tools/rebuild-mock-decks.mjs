/**
 * Rebuild the concept-sandbox sample deck plans from the deckplan-from-positions
 * cache.
 *
 * The cache converts every railcar in the legacy seatmap corpus to a NeTEx
 * `DeckPlan` fragment and keys each one three ways. `latticeKey` is the key that
 * matters here: it hashes the derived grid — band counts plus every spot's
 * class, label and cell — so two railcars sharing it "would import as the same
 * seating plan". Shipping one fragment per distinct `latticeKey` gives a sample
 * set in which no two decks render alike.
 *
 * Run: `node concept-sandbox/tools/rebuild-mock-decks.mjs`, then `npm run
 * format` — `JSON.stringify` expands short arrays Prettier keeps on one line,
 * so the rewritten database fails `npm run check` until it is reformatted.
 *
 * Writes `concept-sandbox/mock-xml/<Owner>-DeckPlan-<n>.decks.xml`, the source
 * artwork beside it as `<Owner>-DeckPlan-<n>.svg`, and rewrites the `deckPlans`
 * array in `concept-sandbox/mock-db-stem.json`. Idempotent: a second run against
 * the same cache produces byte-identical output.
 *
 * The artwork is the legacy system's own drawing of that railcar, copied
 * verbatim. It is the reference the derived fragment is read against — the
 * Deck-Rendering page shows the two side by side — so it is never rewritten,
 * minified or re-scaled here: a transform that changed what it shows would
 * destroy the only thing it is good for.
 *
 * Fragments are read with regular expressions rather than an XML parser. They
 * are machine-generated by one emitter with a fixed shape, only element counts
 * are needed, and the alternative is a dependency the sandbox does not have.
 */
import { copyFileSync, readFileSync, writeFileSync, readdirSync, rmSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

/** Repo root, two levels above this file. */
const REPO = resolve(dirname(fileURLToPath(import.meta.url)), '../..');

/** Where the rebuilt fragments and the mock database live. */
const XML_DIR = join(REPO, 'concept-sandbox/mock-xml'),
  DB = join(REPO, 'concept-sandbox/mock-db-stem.json');

/**
 * Owner organisation preferred *against* — a family held by any operating
 * company ships that company's copy, and org 1 is the fallback for the families
 * no operator holds.
 */
const FALLBACK_ORG = 1;

/** First `NMR:DeckPlan:<n>`, clear of the hand-written stubs at 1/3/4/5. */
const ID_BASE = 100;

/** Codespace and type of an emitted deck-plan id. */
const ID_PREFIX = 'NMR:DeckPlan:';

/**
 * Files this script owns — a fragment and its artwork; anything else in
 * `mock-xml/` is left alone.
 */
const OWNED = /-DeckPlan-\d+\.(decks\.xml|svg)$/;

/** Editor-native samples kept as the set's only non-emitter contrast case. */
const KEEP = /^Xatellite-/;

/** `LocatableSpotType` wire value → singular, plural. */
const SPOT_WORDS = {
  seat: ['seat', 'seats'],
  bed: ['berth', 'berths'],
  luggageSpace: ['luggage bay', 'luggage bays'],
  pushchairSpace: ['pushchair bay', 'pushchair bays'],
  bicycleSpace: ['bicycle bay', 'bicycle bays'],
  wheelchairSpace: ['wheelchair bay', 'wheelchair bays'],
};

/**
 * `PassengerSpaceType` wire value → singular, plural.
 *
 * Insertion order is the order they are listed in: what the deck is *for*
 * first, plumbing last. Ordering these by count instead put "service space"
 * ahead of "seating area" on most cars.
 */
const SPACE_WORDS = {
  seatingArea: ['seating area', 'seating areas'],
  restaurant: ['restaurant', 'restaurants'],
  toilet: ['toilet', 'toilets'],
  other: ['service space', 'service spaces'],
};

/**
 * Locate the corpus. Mirrors `scripts/root.ts` in the skill: the environment
 * override wins, else the nearest ancestor of the cwd holding a manifest, else
 * a sibling checkout of the skills repo beside this one.
 * @returns {string} Directory containing `cache/manifest.json`.
 * @throws {Error} If no corpus is found.
 */
const findRoot = () => {
  const has = d => {
    try {
      readFileSync(join(d, 'cache/manifest.json'));
      return true;
    } catch {
      return false;
    }
  };
  const cands = [];
  if (process.env.SEATMAP_DATA_ROOT) cands.push(resolve(process.env.SEATMAP_DATA_ROOT));
  for (let d = process.cwd(); ; d = dirname(d)) {
    cands.push(d);
    if (d === dirname(d)) break;
  }
  cands.push(resolve(REPO, '../iteru-skills'));
  const hit = cands.find(has);
  if (!hit)
    throw new Error(
      'No seatmap corpus found. Set SEATMAP_DATA_ROOT to a directory holding cache/manifest.json.'
    );
  return hit;
};

/**
 * Read every organisation's key index, tagging each row with its owner.
 * @param {string} root Corpus root.
 * @returns {{rows: object[], orgs: Map<number, string>}} Converted railcars and
 *   the organisation names from the manifest.
 */
const readCorpus = root => {
  const manifest = JSON.parse(readFileSync(join(root, 'cache/manifest.json'), 'utf8'));
  const orgs = new Map(manifest.organisations.map(o => [o.id, o.name]));
  const rows = readdirSync(join(root, 'cache'))
    .filter(d => d.startsWith('org-'))
    .flatMap(d => {
      const org = Number(d.slice(4));
      const idx = join(root, 'cache', d, 'deckplans/index.json');
      let parsed;
      try {
        parsed = JSON.parse(readFileSync(idx, 'utf8'));
      } catch {
        return [];
      }
      return parsed.railcars
        .filter(r => r.latticeKey !== null)
        .map(r => ({
          ...r,
          org,
          frag: join(root, 'cache', d, `deckplans/railcar-${r.railcarId}.xml`),
          art: join(root, 'cache', d, `svg/railcar-${r.railcarId}.svg`),
        }));
    });
  return { rows, orgs };
};

/**
 * Group converted railcars by derived seating plan and elect one representative
 * per group.
 * @param {object[]} rows Converted railcars, org-tagged.
 * @returns {object[]} One row per `latticeKey`, carrying `members` — how many
 *   railcars share that plan.
 */
const reps = rows => {
  const fams = new Map();
  for (const r of rows)
    (fams.get(r.latticeKey) ?? fams.set(r.latticeKey, []).get(r.latticeKey)).push(r);
  return [...fams.values()].map(m => {
    const ranked = [...m].sort(
      (a, b) =>
        (a.org === FALLBACK_ORG) - (b.org === FALLBACK_ORG) ||
        a.org - b.org ||
        a.railcarId - b.railcarId
    );
    return { ...ranked[0], members: m.length };
  });
};

/** Count `<Tag>value</Tag>` occurrences by value. @returns {Map<string, number>} */
const tally = (xml, tag) => {
  const out = new Map();
  for (const m of xml.matchAll(new RegExp(`<${tag}>([^<]*)</${tag}>`, 'g')))
    out.set(m[1], (out.get(m[1]) ?? 0) + 1);
  return out;
};

/**
 * Render a tally as prose using a word table.
 * @param {Map<string, number>} counts Wire value → occurrences.
 * @param {Record<string, [string, string]>} words Wire value → singular, plural.
 *   Its key order ranks the output; values it does not name sort last, by count,
 *   and keep their wire form.
 * @param {boolean} [countOne] Whether a count of one is written out. False reads
 *   better for spaces ("seating area"); true is needed for spots, where the
 *   number is the point ("1 wheelchair bay").
 * @returns {string[]} One phrase per value.
 */
const phrases = (counts, words, countOne = true) => {
  const rank = Object.keys(words);
  const at = k => (rank.indexOf(k) + 1 || rank.length + 1) - 1;
  return [...counts]
    .sort((a, b) => at(a[0]) - at(b[0]) || b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([k, n]) => {
      const [one, many] = words[k] ?? [k, k];
      return n === 1 && !countOne ? one : `${n} ${n === 1 ? one : many}`;
    });
};

/**
 * Describe one deck from its fragment and its index row.
 *
 * `(fam:N)` closes every description: N is how many railcars in the corpus share
 * this seating plan, so a reader can tell a one-off from a plan the fleet
 * repeats fourteen times.
 *
 * @param {string} xml The `<decks>` fragment.
 * @param {object} rep The representative's index row.
 * @returns {string} e.g. `68 seats in 17×4 · seating area, 2 toilets · 4 entrances (fam:14)`
 */
const describe = (xml, rep) => {
  const entrances = (xml.match(/<(Passenger)?DeckEntrance\b/g) ?? []).length;
  const segs = [
    `${phrases(tally(xml, 'LocatableSpotType'), SPOT_WORDS).join(', ')} in ${rep.rows}×${rep.columns}`,
    phrases(tally(xml, 'PassengerSpaceType'), SPACE_WORDS, false).join(', '),
    entrances ? `${entrances} ${entrances === 1 ? 'entrance' : 'entrances'}` : '',
  ].filter(Boolean);
  return `${segs.join(' · ')} (fam:${rep.members})`;
};

/**
 * Strip the `DeckPlan` wrapper, leaving the `<decks>` subtree the sandbox stores.
 *
 * `wrapFrag` in `partials/deck-render.html` re-wraps a fragment in `<DeckPlan>`
 * before parsing, so the file must hold that element's children. Dropping the
 * wrapper also drops the provenance `keyList`, which has no consumer here.
 *
 * @param {string} xml A cache fragment, rooted at `<DeckPlan>`.
 * @returns {string} A `<decks>`-rooted document.
 * @throws {Error} If the fragment carries no decks.
 */
const toFragment = xml => {
  const m = xml.match(/^([ \t]*)<decks>[\s\S]*?^\1<\/decks>/m);
  if (!m) throw new Error('fragment holds no <decks>');
  const dedent = new RegExp(`^${m[1]}`, 'gm');
  return `<?xml version="1.0" encoding="utf-8"?>\n${m[0].replace(dedent, '')}\n`;
};

/**
 * Disambiguate names reused by more than one seating plan.
 *
 * A litra names a carriage class, not a layout, so several distinct plans share
 * one. The largest family keeps the bare litra and the rest take an ordinal.
 *
 * @param {object[]} sel Representatives, each carrying `litra` and `members`.
 * @returns {Map<object, string>} Representative → display name.
 */
const names = sel => {
  const byLitra = new Map();
  for (const r of sel) (byLitra.get(r.litra) ?? byLitra.set(r.litra, []).get(r.litra)).push(r);
  const out = new Map();
  for (const [litra, group] of byLitra) {
    const ranked = [...group].sort((a, b) => b.members - a.members || a.railcarId - b.railcarId);
    ranked.forEach((r, i) => out.set(r, i === 0 ? litra : `${litra} (v${i + 1})`));
  }
  return out;
};

const root = findRoot();
const { rows, orgs } = readCorpus(root);
if (!rows.length)
  throw new Error(`No converted railcars under ${root}/cache — run the skill's convert first.`);

/** Stable order: litra, then the railcar behind it, so ids do not move between runs. */
const sel = reps(rows).sort((a, b) => a.litra.localeCompare(b.litra) || a.railcarId - b.railcarId);
const name = names(sel);
const slug = id => (orgs.get(id) ?? `Org${id}`).replace(/[^A-Za-z0-9]/g, '');

mkdirSync(XML_DIR, { recursive: true });
for (const f of readdirSync(XML_DIR)) if (OWNED.test(f) && !KEEP.test(f)) rmSync(join(XML_DIR, f));

/** Railcars whose artwork the cache does not hold, reported after the run. */
const artless = [];

const plans = sel.map((rep, i) => {
  const frag = toFragment(readFileSync(rep.frag, 'utf8'));
  const stem = `${slug(rep.org)}-DeckPlan-${ID_BASE + i}`;
  writeFileSync(join(XML_DIR, `${stem}.decks.xml`), frag);

  // Artwork is served per organisation and a corpus can be fetched without it,
  // so a missing drawing is a gap in the cache rather than a fault: the plan
  // ships with no `svgRef` and the render page shows the fragment alone.
  let art;
  try {
    copyFileSync(rep.art, join(XML_DIR, `${stem}.svg`));
    art = `mock-xml/${stem}.svg`;
  } catch {
    artless.push(name.get(rep));
  }

  return {
    id: `${ID_PREFIX}${ID_BASE + i}`,
    name: name.get(rep),
    description: describe(frag, rep),
    deckCount: 1,
    decksRef: `mock-xml/${stem}.decks.xml`,
    ...(art && { svgRef: art }),
  };
});

const db = JSON.parse(readFileSync(DB, 'utf8'));
const kept = db.deckPlans.filter(
  p => !p.decksRef || KEEP.test(p.decksRef.replace('mock-xml/', ''))
);
db.deckPlans = [...kept, ...plans].sort((a, b) => a.name.localeCompare(b.name));
writeFileSync(DB, `${JSON.stringify(db, null, 2)}\n`);

console.log(
  `${plans.length} fragments from ${root}\n` +
    `kept ${kept.length} existing (${kept.filter(p => !p.decksRef).length} stubs)\n` +
    [...new Set(sel.map(r => r.org))]
      .sort((a, b) => a - b)
      .map(o => `  ${orgs.get(o) ?? o}: ${sel.filter(r => r.org === o).length}`)
      .join('\n') +
    (artless.length ? `\nno artwork in the cache for: ${artless.join(', ')}` : '')
);
